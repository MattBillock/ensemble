/**
 * Get a random fact from any category or a specific category
 * @param {string} category - Optional category to filter by
 * @returns {Object} A random fact {title, fact}
 */
export const getRandomFact = (category = null) => {
  const facts = category && FACTS_BY_CATEGORY[category]
    ? FACTS_BY_CATEGORY[category]
    : ALL_FACTS;
  return facts[Math.floor(Math.random() * facts.length)];
};

/**
 * Get the next fact in rotation
 * @param {number} currentIndex - Current fact index
 * @param {string} category - Optional category to filter by
 * @returns {Object} {fact, nextIndex}
 */
export const getNextFact = (currentIndex, category = null) => {
  const facts = category && FACTS_BY_CATEGORY[category]
    ? FACTS_BY_CATEGORY[category]
    : ALL_FACTS;
  const nextIndex = (currentIndex + 1) % facts.length;
  return { fact: facts[nextIndex], nextIndex };
};

